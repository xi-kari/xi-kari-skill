/* Run with node tests/test_reader_interaction.cjs <jsdom module path> [python]. */
'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { JSDOM, VirtualConsole } = require(process.argv[2] || 'jsdom');
const python = process.argv[3] || 'python';
const root = path.resolve(__dirname, '..');
const source = '# 可继续讨论的完整文章\n\n## 主体\n\n可复算原式 \\(x^2\\)，保留价格 $5 与 $10 和注释[^a]。\n\n再次引用[^a]。\n\n$$\\frac{a}{b}$$\n\n错误原式 \\(\\unknownCommand{x}\\)。\n\n```text\n$x$ 是代码\n```\n\n## 后一节\n\n后文完整保留。\n\n| 方案 | 工时 | 人数 |\n| --- | --- | --- |\n| A | 10 | 2 |\n\n[^a]: 证据说明。\n';
const render = spawnSync(python, ['-c', 'import importlib.util,sys; from pathlib import Path; s=importlib.util.spec_from_file_location("reader",sys.argv[1]); m=importlib.util.module_from_spec(s); s.loader.exec_module(m); sys.stdout.reconfigure(encoding="utf-8"); print(m.render_document(sys.stdin.read()))', path.join(root, 'scripts/render_answer.py')], { input: source, encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 });
assert.equal(render.status, 0, render.stderr);
const errors = [], copied = [];
const virtualConsole = new VirtualConsole();
virtualConsole.on('jsdomError', error => errors.push(error.message.slice(0, 200)));
const dom = new JSDOM(render.stdout, {
  runScripts: 'dangerously', url: 'https://example.invalid/reader-test', pretendToBeVisual: true, virtualConsole,
  beforeParse(window) {
    window.fetch = () => { throw new Error('Network must not be used'); };
    window.HTMLElement.prototype.scrollIntoView = function () {};
    window.HTMLElement.prototype.getBoundingClientRect = function () { return { height: this.classList.contains('reader-toolbar') ? 124 : 0, top: 0, bottom: 0, width: 800, left: 0, right: 800 }; };
    window.ResizeObserver = class { constructor(callback) { this.callback = callback; } observe() { this.callback(); } };
    Object.defineProperty(window.navigator, 'clipboard', { value: { writeText: async text => { copied.push(text); } }, configurable: true });
  }
});

(async () => {
  const window = dom.window, document = window.document;
  assert.equal(errors.length, 0, errors.join('\n'));
  assert.equal(document.querySelectorAll('[data-math-rendered="true"]').length, 2);
  assert.equal(document.querySelectorAll('.math-error').length, 1);
  assert.ok(document.querySelector('.math-error').textContent.includes('unknownCommand'));
  assert.ok(document.getElementById('document').textContent.includes('价格 $5 与 $10'));
  assert.equal(document.querySelectorAll('.footnote-ref').length, 2);
  const identifiers = [...document.querySelectorAll('[id]')].map(element => element.id);
  assert.equal(identifiers.length, new Set(identifiers).size);
  document.querySelectorAll('.footnote-ref a, .footnote-backref').forEach(link => assert.ok(document.getElementById(link.hash.slice(1))));
  assert.equal(document.documentElement.style.getPropertyValue('--toolbar-height'), '124px');
  const paragraph = [...document.querySelectorAll('#document > p')].find(element => element.textContent.includes('可复算原式'));
  const range = document.createRange(); range.selectNodeContents(paragraph);
  window.getSelection().removeAllRanges(); window.getSelection().addRange(range);
  document.dispatchEvent(new window.Event('selectionchange'));
  document.getElementById('quote-question').click();
  const textarea = document.getElementById('question-text');
  assert.equal(document.getElementById('question-panel').hidden, false);
  assert.ok(textarea.value.includes('作品：《可继续讨论的完整文章》'));
  assert.ok(textarea.value.includes('主体（#section-'));
  assert.equal(textarea.value.split('\\(x^2\\)').length - 1, 1);
  assert.ok(textarea.value.includes('[^a]'));
  assert.ok(!textarea.value.includes('返回引用'));
  document.getElementById('copy-question').click(); await new Promise(resolve => setTimeout(resolve, 0));
  assert.equal(copied.length, 1);
  assert.equal(copied[0], textarea.value);
  Object.defineProperty(window.navigator, 'clipboard', { value: { writeText: async () => { throw new Error('Unavailable'); } }, configurable: true });
  document.getElementById('copy-question').click(); await new Promise(resolve => setTimeout(resolve, 0));
  assert.ok(document.getElementById('question-status').textContent.includes('Ctrl+C'));
  assert.equal(textarea.selectionStart, 0); assert.equal(textarea.selectionEnd, textarea.value.length);
  document.getElementById('close-question').click();
  assert.equal(document.getElementById('question-panel').hidden, true);
  assert.equal(document.activeElement.id, 'quote-question');
  document.getElementById('quote-question').click();
  const select = document.getElementById('question-section');
  select.value = [...select.options].find(option => option.textContent === '主体').value;
  select.dispatchEvent(new window.Event('change'));
  document.getElementById('quote-section').click();
  assert.ok(textarea.value.includes('可复算原式'));
  assert.ok(!textarea.value.includes('后文完整保留'));
  select.value = [...select.options].find(option => option.textContent === '后一节').value;
  select.dispatchEvent(new window.Event('change'));
  document.getElementById('quote-section').click();
  assert.ok(textarea.value.includes('A\t10\t2'));
  assert.ok(!textarea.value.includes('A102'));
  assert.ok(!textarea.value.includes('证据说明'));
  const note = document.querySelector('.footnotes li p');
  const noteRange = document.createRange(); noteRange.selectNodeContents(note);
  window.getSelection().removeAllRanges(); window.getSelection().addRange(noteRange);
  document.dispatchEvent(new window.Event('selectionchange'));
  document.getElementById('quote-question').click();
  assert.ok(textarea.value.includes('章节位置：脚注 [^a]（#fn-'));
  assert.ok(!textarea.value.includes('章节位置：后一节'));
  const formulaCount = document.querySelectorAll('.katex').length;
  const search = document.getElementById('reader-search');
  search.value = 'x^2'; search.dispatchEvent(new window.Event('input'));
  await new Promise(resolve => setTimeout(resolve, 200));
  assert.ok(document.querySelector('.reader-math.current-match'));
  assert.equal(document.querySelectorAll('.katex').length, formulaCount);
  search.value = ''; search.dispatchEvent(new window.Event('input'));
  await new Promise(resolve => setTimeout(resolve, 200));
  assert.equal(document.querySelectorAll('.current-match').length, 0);
  document.getElementById('theme-toggle').click();
  assert.equal(document.documentElement.dataset.theme, 'night');
  document.getElementById('font-larger').click();
  assert.equal(document.documentElement.dataset.font, 'large');
  const original = document.querySelector('a.source-download').href.split(',')[1];
  assert.equal(Buffer.from(original, 'base64').toString('utf8'), source);
  assert.equal(errors.length, 0, errors.join('\n'));
  console.log('Reader DOM checks passed: offline math, footnotes, selection quotation, clipboard fallback, keyboard section, search, theme, source preservation.');
  window.close();
})().catch(error => { dom.window.close(); console.error(error.stack); process.exitCode = 1; });
